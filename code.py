@torch.no_grad()
def extract_features_fast(model, loader, device):
    model.eval()

    # Get feature dimension
    sample_batch = next(iter(loader))[0].to(device)
    _, sample_feat = model(sample_batch)
    feat_dim = sample_feat.shape[1]

    total_samples = len(loader.dataset)
    features = torch.empty((total_samples, feat_dim), dtype=torch.float32)

    idx = 0
    for x, _ in loader:
        bsz = x.size(0)
        x = x.to(device, non_blocking=True)

        _, f = model(x)
        features[idx:idx+bsz] = f.cpu()
        idx += bsz

    return features.numpy()

