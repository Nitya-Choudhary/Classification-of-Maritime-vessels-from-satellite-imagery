@torch.no_grad()
def compute_ship_centroid_fast(model, loader):
    model.eval()

    feat_sum = None
    count = 0

    for x, y in loader:
        # Move only once
        x = x.to(DEVICE)
        y = y.to(DEVICE)

        # Forward pass
        _, feats = model(x)

        # Select only ship features
        ship_feats = feats[y == 1]

        if ship_feats.numel() == 0:
            continue

        if feat_sum is None:
            feat_sum = ship_feats.sum(dim=0)
        else:
            feat_sum += ship_feats.sum(dim=0)

        count += ship_feats.size(0)

    # Final centroid
    centroid = (feat_sum / count).cpu().numpy()
    return centroid

